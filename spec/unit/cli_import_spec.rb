require 'spec_helper'
require 'api_recipes/cli'

describe 'api_recipes import' do
  let(:small) { fixture_openapi('github_small.yml') }

  def configure_with(yaml)
    configure_test_apis(ApiRecipes::Internals::Compiler.normalize(YAML.safe_load(yaml), :options_map))
  end

  it 'writes the recipe of the design example on STDOUT' do
    code, out, err = run_cli('import', small, '--name', 'github')
    expect(code).to eq(0)
    expect(YAML.safe_load(out)).to eq(YAML.safe_load(File.read(fixture_openapi('github_small.expected.yml'))))
    expect(out).to include('# GET /users/{username} (users/get-by-username)', '# POST /repos/{owner}/{repo}/issues')
    expect(out.lines.first).to eq("# Generated by api_recipes import from GitHub 1.0\n")
    expect(err).to eq("7 operations imported from 5 paths\n")
  end

  describe 'with --calls' do
    it 'writes under each endpoint how it is called, and the same recipe' do
      _, plain, = run_cli('import', small, '--name', 'github')
      code, out, err = run_cli('import', small, '--name', 'github', '--calls')
      expect([code, err]).to eq([0, "7 operations imported from 5 paths\n"])
      expect(YAML.safe_load(out)).to eq(YAML.safe_load(plain))
      expect(out.lines - plain.lines).to all(match(/\A +# \.[\w.(), ]+\n\z/))
      expect(out).to include("# GET /users/{username} (users/get-by-username)\n#{' ' * 34}# .users.show(username)\n")
      expect(out.lines.grep(/\A +# \./).map(&:strip)).to include('# .users', '# .users.repos(username)', '# .repos.issues(owner, repo)',
                                                                  '# .repos.issues(owner, repo).show(issue_number)')
      expect(plain).not_to match(/# \./)
    end

    it 'writes calls that can be made as they are written, one for each call of the recipe' do
      _, out, = run_cli('import', small, '--name', 'github', '--calls')
      configure_with(out)
      calls = out.lines.grep(/\A +# \./).map { |line| line.strip.delete_prefix('# ') }
      expect(calls.size).to eq(ApiRecipes.github.definition.routes.size)
      urls = calls.map { |call| ApiRecipes.github.instance_eval("self#{call.gsub(/\w+(?=[,)])/, "'x'")}").url.to_s }
      expect(urls).to all(start_with('https://api.github.com/'))
    end

    it 'writes none under an endpoint that is only a group' do
      _, out, = run_cli('import', small, '--name', 'github', '--calls')
      expect(out).to include("    repos:\n      route: false\n")
    end
  end

  it 'produces a recipe that the gem loads and that offers the calls of the design' do
    _, out, = run_cli('import', small, '--name', 'github')
    configure_with(out)
    github = ApiRecipes.github
    expect(github.users.url.to_s).to eq('https://api.github.com/users')
    expect(github.users.show('octocat').url.to_s).to eq('https://api.github.com/users/octocat')
    expect(github.users.repos('octocat').url.to_s).to eq('https://api.github.com/users/octocat/repos')
    expect(github.repos.issues('rails', 'rails').url.to_s).to eq('https://api.github.com/repos/rails/rails/issues')
    expect(github.repos.issues('rails', 'rails').show(1347).url.to_s)
      .to eq('https://api.github.com/repos/rails/rails/issues/1347')
    create = github.repos.issues('rails', 'rails').create
    expect([create.definition.verb, create.definition.ok_code, create.url.to_s])
      .to eq([:post, 201, 'https://api.github.com/repos/rails/rails/issues'])
    expect(github.repos.issues('rails', 'rails').update(1347).definition.verb).to eq(:patch)
    expect(github.repos.definition.route?).to be(false)
  end

  it 'names the api after the title of the description, or as asked' do
    with_description(openapi('info' => { 'title' => 'My Shop API (v2)', 'version' => '2' })) do |path|
      expect(YAML.safe_load(run_cli('import', path)[1]).keys).to eq(['my_shop_api_v2'])
      expect(YAML.safe_load(run_cli('import', path, '--name', 'shop')[1]).keys).to eq(['shop'])
    end
    with_description(openapi('info' => { 'title' => '!!!', 'version' => '2' })) do |path|
      expect(YAML.safe_load(run_cli('import', path)[1]).keys).to eq(['api'])
    end
    with_description(openapi('info' => { 'title' => '2nd API', 'version' => '2' })) do |path|
      expect(YAML.safe_load(run_cli('import', path)[1]).keys).to eq(['api_2nd_api'])
    end
  end

  it 'refuses a name that is not a method name, as a wrong argument' do
    ['my api', '2nd', 'a-b', ''].each do |name|
      code, out, err = run_cli('import', small, '--name', name)
      expect([code, out]).to eq([2, ''])
      expect(err).to match(/--name/)
    end
  end

  it 'says so when the name of the api is a method of ApiRecipes' do
    code, _, err = run_cli('import', small, '--name', 'configure')
    expect(code).to eq(0)
    expect(err).to match(/warning: .*'configure'.*ApiRecipes\[/)
  end

  it 'takes the filters, more than once' do
    code, out, err = run_cli('import', small, '--name', 'github', '--only', 'users*', '--only', 'repos/*', '--except', '*issues')
    expect(code).to eq(0)
    configure_with(out)
    expect(ApiRecipes.github.definition.routes.map(&:call))
      .to eq(['github.users', 'github.users.show(username)', 'github.users.repos(username)',
              'github.repos.issues(owner, repo).show(issue_number)', 'github.repos.issues(owner, repo).update(issue_number)'])
    expect(err).to eq("5 operations imported from 4 paths, 2 left out by the filters\n")
  end

  it 'takes the server that was asked for' do
    servers = [{ 'url' => 'https://one.example.test' }, { 'url' => 'http://two.example.test:8080/v2' }]
    with_description(openapi('servers' => servers)) do |path|
      expect(YAML.safe_load(run_cli('import', path, '--server', '1')[1])['test_api'])
        .to include('protocol' => 'http', 'host' => 'two.example.test', 'port' => 8080, 'base_url' => 'v2')
      code, out, err = run_cli('import', path, '--server', '2')
      expect([code, out]).to eq([1, ''])
      expect(err).to match(/--server 2/)
    end
  end

  it 'writes the auth and the variables of the description' do
    text = openapi('servers' => [{ 'url' => 'https://{shop}.example.test', 'variables' => { 'shop' => { 'default' => 'acme' } } }],
                   'components' => { 'securitySchemes' => { 'key' => { 'type' => 'apiKey', 'in' => 'header', 'name' => 'X-Key' } } },
                   'security' => [{ 'key' => [] }])
    with_description(text) do |path|
      code, out, = run_cli('import', path, '--name', 'shop')
      expect(code).to eq(0)
      configure_with(out)
      expect(ApiRecipes.shop.users.url.to_s).to eq('https://acme.example.test/users')
      expect(ApiRecipes.shop.definition.auth).to eq(type: :header, name: 'X-Key')
    end
  end

  it 'prints the warnings and the summary on STDERR, never on STDOUT' do
    with_description(openapi('servers' => [{ 'url' => '/v1' }],
                             'paths' => { '/with' => { 'get' => {} }, '/a/{id}_x' => { 'get' => {} } })) do |path|
      code, out, err = run_cli('import', path)
      expect(code).to eq(0)
      expect(out).not_to match(/warning|imported/)
      expect(err.lines.grep(/\Awarning: /).size).to eq(3)
      expect(err.lines.last).to eq("1 operation imported from 2 paths, 3 warnings\n")
    end
  end

  it 'says so when nothing was imported' do
    code, out, err = run_cli('import', small, '--only', 'nothing*')
    expect(code).to eq(0)
    expect(YAML.safe_load(out)).to eq('github' => { 'recipe' => { 'name' => 'github', 'version' => '1.0.0', 'format' => 1 }, 'host' => 'api.github.com' })
    expect(err).to match(/warning: no operation was imported/)
  end

  it 'imports a description whose schemas refer to themselves, and one written with aliases' do
    schemas = { 'Node' => { 'properties' => { 'next' => { '$ref' => '#/components/schemas/Node' } } } }
    with_description(openapi('components' => { 'schemas' => schemas })) do |path|
      expect(run_cli('import', path).first).to eq(0)
    end
    aliased = "openapi: 3.0.3\ninfo: {title: T, version: '1'}\nx-ok: &ok {responses: {'200': {description: ok}}}\n" \
              "paths:\n  /a: {get: *ok}\n  /b: {get: *ok, post: *ok}\n"
    with_description(aliased) do |path|
      code, _, err = run_cli('import', path)
      expect([code, err]).to eq([0, "warning: the description names no server: the host is the variable {host}, to give with config.values\n" \
                                    "3 operations imported from 2 paths, 1 warning\n"])
    end
  end

  it 'reads a JSON description' do
    with_description(JSON.generate(YAML.safe_load(File.read(small))), 'openapi.json') do |path|
      code, out, = run_cli('import', path, '--name', 'github')
      expect(code).to eq(0)
      expect(YAML.safe_load(out)).to eq(YAML.safe_load(File.read(fixture_openapi('github_small.expected.yml'))))
    end
  end

  describe '--output' do
    it 'writes the recipe in a new file and nothing on STDOUT' do
      Dir.mktmpdir do |dir|
        target = File.join(dir, 'github.yml')
        code, out, err = run_cli('import', small, '--name', 'github', '--output', target)
        expect([code, out]).to eq([0, ''])
        expect(YAML.safe_load(File.read(target)).keys).to eq(['github'])
        expect(err).to match(/7 operations imported/)
      end
    end

    it 'does not replace a file that exists' do
      Dir.mktmpdir do |dir|
        target = File.join(dir, 'github.yml')
        File.write(target, 'mine')
        code, out, err = run_cli('import', small, '--output', target)
        expect([code, out, File.read(target)]).to eq([2, '', 'mine'])
        expect(err).to match(/github\.yml already exists/)
      end
    end

    it 'writes nothing when the description cannot be imported' do
      Dir.mktmpdir do |dir|
        target = File.join(dir, 'out.yml')
        with_description(YAML.dump('swagger' => '2.0')) do |path|
          expect(run_cli('import', path, '--output', target).first).to eq(1)
        end
        expect(File.exist?(target)).to be(false)
      end
    end
  end

  it 'exits with 1 and writes nothing when the description cannot be imported' do
    with_description(YAML.dump('swagger' => '2.0', 'paths' => {})) do |path|
      code, out, err = run_cli('import', path)
      expect([code, out]).to eq([1, ''])
      expect(err).to match(/Swagger 2\.0 is not supported/)
    end
  end

  it 'exits with 2 for wrong arguments and for a file it cannot read' do
    expect(run_cli('import').values_at(0, 1)).to eq([2, ''])
    expect(run_cli('import', small, small).first).to eq(2)
    expect(run_cli('import', small, '--bogus').first).to eq(2)
    expect(run_cli('import', small, '--server', 'two').first).to eq(2)
    code, out, err = run_cli('import', '/nonexistent/openapi.yml')
    expect([code, out]).to eq([2, ''])
    expect(err).to match(%r{/nonexistent/openapi\.yml: no such file})
  end

  it 'stops quietly when the reader of its output goes away' do
    out = StringIO.new
    allow(out).to receive(:write).and_raise(Errno::EPIPE)
    err = StringIO.new
    expect(ApiRecipes::CLI.run(['import', small], out: out, err: err)).to eq(0)
    expect(err.string).not_to match(/EPIPE|cannot be written/)
  end

  it 'is described by the help' do
    _, out, = run_cli('--help')
    expect(out).to include('import [--name NAME]', '--only GLOB', '--except GLOB', '--server N', '--calls', '--output FILE')
  end

  it 'is not loaded with the library' do
    lib = File.expand_path('../../lib', __dir__)
    loaded = `#{RbConfig.ruby} -I #{lib} #{$LOAD_PATH.select { |p| File.directory?(p) }.map { |p| "-I #{p}" }.join(' ')} -e 'require "api_recipes"; print defined?(ApiRecipes::CLI).inspect, $LOADED_FEATURES.grep(/api_recipes\\/cli/).size'`
    expect(loaded).to eq('nil0')
  end
end
