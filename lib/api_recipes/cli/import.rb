# frozen_string_literal: true

require 'date'

module ApiRecipes
  module CLI
    # The import command: writes a recipe from an OpenAPI description. The
    # description is read once, from one local file, and nothing in it is run.
    class Import
      # The description cannot be imported. The message says where and why.
      class Error < ApiRecipes::Error; end

      Result = Data.define(:text, :warnings, :summary)
      MAX_WARNINGS = 100

      # calls: write beside each endpoint how it is called in Ruby.
      # version: the version of the recipe that is written.
      def initialize(path, name: nil, only: [], except: [], server: 0, calls: false, version: Convert::DEFAULT_VERSION)
        @version = version
        @path = path
        @name = name
        @only = only
        @except = except
        @server = server
        @calls = calls
      end

      # Reads the description and returns the text of the recipe with the
      # warnings and the summary. Raises Error when it cannot be imported:
      # nothing is returned unless the text is a recipe the gem accepts.
      def call
        document = Document.load(@path)
        name, warnings = api_name(document)
        server = Server.read(document, @server)
        security = Security.read(document)
        tree = Tree.build(document, only: @only, except: @except)
        raise Error, '--version: must be made of digits, letters and dots, such as 1.2.0' unless Internals::Recipe::VERSION.match?(@version.to_s)

        options = { recipe: { 'name' => name, 'version' => @version, 'format' => Internals::Recipe::FORMAT } }.merge(server.options)
        options[:auth] = security.auth if security.auth
        header = "Generated by api_recipes import from #{document.title} #{document.version}"
        text = Writer.new(name: name, options: options, nodes: tree.nodes, header: header).to_yaml
        compiled = verify(text)
        if @calls
          # The calls are those of the recipe just written and checked. The
          # writer reads its text back: the comments leave the data as it is.
          calls = Calls.of(compiled)
          text = Writer.new(name: name, options: options, nodes: tree.nodes, header: header, calls: calls).to_yaml
        end
        warnings += server.warnings + security.warnings + tree.warnings
        warnings << 'no operation was imported' if tree.operations.zero?
        Result.new(text: text, warnings: shown_warnings(warnings), summary: summary(tree, warnings.size))
      end

      private

      # [name, warnings]. The name given with --name, or the title of the
      # description in lower case with underscores, or "api".
      def api_name(document)
        name = @name
        if name.nil?
          name = Import.one_line(document.title).downcase.gsub(/[^a-z0-9]+/, '_').gsub(/\A_+|_+\z/, '')
          name = 'api' if name.empty?
          name = "api_#{name}" if name.match?(/\A\d/)
        end
        unless name.is_a?(String) && Internals::Compiler::METHOD_NAME.match?(name) && Internals::Recipe::NAME.match?(name)
          raise Error, '--name: must be the name of a recipe and of a method: lowercase letters, digits and _, not starting with a digit'
        end

        warnings = []
        if Internals::Handles.taken?(ApiRecipes.singleton_class, name.to_sym)
          warnings << "#{Import.shown(name)} is the name of a method of ApiRecipes: reach the api with ApiRecipes[:#{name}]"
        end
        [name, warnings]
      end

      # A description can be made to produce any number of warnings.
      def shown_warnings(warnings)
        return warnings if warnings.size <= MAX_WARNINGS

        warnings.first(MAX_WARNINGS) + ["#{warnings.size - MAX_WARNINGS} more warnings were not shown"]
      end

      # The text must be a recipe that the gem compiles.
      # What is written is a portable recipe: it is checked as one. Returns
      # its compiled tree.
      def verify(text)
        file_name = "#{YAML.safe_load(text).keys.first}#{Internals::Recipe::SUFFIX}"
        Internals::Recipe.parse(text, file_name, file_name: file_name).definition
      rescue ConfigurationError => e
        raise Error, "the recipe would not be valid, so nothing was written:\n#{e.errors.map { |problem| "  #{problem}" }.join("\n")}"
      end

      def summary(tree, warnings)
        text = "#{count(tree.operations, 'operation')} imported from #{count(tree.paths, 'path')}"
        text += ", #{tree.skipped} left out by the filters" if tree.skipped.positive?
        text += ", #{count(warnings, 'warning')}" if warnings.positive?
        text
      end

      def count(number, word) = "#{number} #{word}#{'s' unless number == 1}"

      # The text of a plain value of the description, or nil for a mapping or
      # a list. Mappings and lists are never turned into text: with YAML
      # aliases a small file can describe a structure too large to print.
      # Every value read from a description goes through this method, shown or
      # one_line, never through to_s or an interpolation.
      def self.text(value)
        case value
        when String then value
        when Symbol, Numeric, true, false, Date, Time then value.to_s
        end
      end

      # A value of the description as it is shown in a message: one line of
      # printable characters, cut to a length that keeps the message readable.
      def self.shown(value)
        text = self.text(value)
        return value.nil? ? 'nothing' : "a #{value.is_a?(Hash) ? 'mapping' : 'list'}" if text.nil?

        text = text.scrub('?').gsub(/[^[:print:]]/, '?')
        "'#{text.length > 80 ? "#{text[0, 80]}..." : text}'"
      end

      # Free text of the description (a title, a description, an operationId)
      # as it may appear in the recipe: one line, without control characters
      # and without the ERB delimiters, which a recipe file would evaluate.
      # Every kind of space and of line separator becomes one space, and so do
      # the characters that are not shown or that change the direction of text.
      def self.one_line(value, limit = 200)
        text = self.text(value).to_s.scrub('?').gsub(/[[:cntrl:][:space:]\p{Cf}\p{Zl}\p{Zp}]+/, ' ')
        text = text.gsub(/<%|%>/, '') while text.match?(/<%|%>/)
        text.strip[0, limit]
      end
    end
  end
end

